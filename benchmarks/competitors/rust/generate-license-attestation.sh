set -eu

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_root=$(CDPATH= cd -- "$script_dir/../../.." && pwd)
cd "$script_dir"

fail()
{
  printf 'Rust license attestation generation failed: %s\n' "$1" >&2
  exit 1
}

for required_tool in awk cargo cmp cut diff dirname jq mktemp sed sort tar; do
  command -v "$required_tool" >/dev/null 2>&1 || fail "required tool is unavailable: $required_tool"
done

digest_file()
{
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | awk '{print $1}'
  else
    fail "neither sha256sum nor shasum is available"
  fi
}

validate_selection()
{
  case "$1|$2" in
    'MIT|MIT' | \
    'Zlib|Zlib' | \
    'Apache-2.0|Apache-2.0' | \
    'MIT OR Apache-2.0|MIT' | \
    'Apache-2.0 OR MIT|MIT' | \
    'Apache-2.0/MIT|MIT' | \
    'MIT/Apache-2.0|MIT' | \
    'Unlicense OR MIT|MIT' | \
    'MIT OR Apache-2.0 OR LGPL-2.1-or-later|MIT' | \
    'Apache-2.0 OR BSL-1.0|BSL-1.0' | \
    'Zlib OR Apache-2.0 OR MIT|MIT' | \
    'MIT OR Apache-2.0 OR Zlib|MIT' | \
    '(MIT OR Apache-2.0) AND Unicode-3.0|MIT AND Unicode-3.0' | \
    'Apache-2.0 WITH LLVM-exception OR Apache-2.0 OR MIT|MIT' | \
    'BSD-2-Clause OR Apache-2.0 OR MIT|MIT')
      return
      ;;
    *)
      fail "unreviewed SPDX selection: manifest '$1', selected '$2'"
      ;;
  esac
}

temporary_root=$(mktemp -d "${TMPDIR:-/tmp}/flyology-json-rust-license-attestation.XXXXXX")
trap 'rm -rf "$temporary_root"' EXIT HUP INT TERM

cargo metadata --locked --offline --format-version 1 >"$temporary_root/metadata.json"
jq -r \
  '.packages[] | [.name, .version, (.source // "LOCAL"), (.license // "MISSING"), .manifest_path] | @tsv' \
  "$temporary_root/metadata.json" | LC_ALL=C sort >"$temporary_root/metadata.tsv"

awk '
  function value(line) {
    sub(/^[^\"]*\"/, "", line)
    sub(/\".*$/, "", line)
    return line
  }
  function emit() {
    if (!active) return
    if (name == "" || version == "") exit 2
    if (source == "") source = "LOCAL"
    if (checksum == "") checksum = "LOCAL"
    print name "\t" version "\t" source "\t" checksum
  }
  /^\[\[package\]\]$/ {
    emit()
    active = 1
    name = version = source = checksum = ""
    next
  }
  active && /^name = "/ { name = value($0); next }
  active && /^version = "/ { version = value($0); next }
  active && /^source = "/ { source = value($0); next }
  active && /^checksum = "/ { checksum = value($0); next }
  END { emit() }
' Cargo.lock | LC_ALL=C sort >"$temporary_root/lock.tsv" || fail "Cargo.lock package parsing failed"

cut -f 1-3 "$temporary_root/metadata.tsv" >"$temporary_root/metadata-packages"
cut -f 1-3 "$temporary_root/lock.tsv" >"$temporary_root/lock-packages"
diff -u "$temporary_root/lock-packages" "$temporary_root/metadata-packages" >/dev/null ||
  fail "Cargo.lock and the complete Cargo metadata graph differ"

sed -e '/^#/d' -e '/^$/d' license-policy.tsv | LC_ALL=C sort >"$temporary_root/policy.tsv"
awk -F '\t' 'NF != 7 { exit 1 }' "$temporary_root/policy.tsv" ||
  fail "license-policy.tsv must have exactly seven tab-separated fields"
cut -f 1,2 "$temporary_root/policy.tsv" | LC_ALL=C sort -u >"$temporary_root/policy-packages"
cut -f 1,2 "$temporary_root/metadata.tsv" | LC_ALL=C sort -u >"$temporary_root/metadata-package-versions"
diff -u "$temporary_root/metadata-package-versions" "$temporary_root/policy-packages" >/dev/null ||
  fail "license-policy.tsv does not cover the exact resolved package graph"

printf '# Generated by generate-license-attestation.sh; review license-policy.tsv instead of editing this file.\n'
printf '# package\tversion\tsource\tlock checksum\tmanifest license expression\tselected branch\trequired license\tevidence role\tevidence path\tevidence SHA-256\n'

current_key=
current_root=
current_source=
current_checksum=
current_archive=
current_prefix=

while IFS="$(printf '\t')" read -r package version expected_manifest selected required_license role evidence_path; do
  key="$package\t$version"
  if [ "$key" != "$current_key" ]; then
    metadata_line=$(awk -F '\t' -v package="$package" -v version="$version" \
      '$1 == package && $2 == version { print; found++ } END { if (found != 1) exit 1 }' \
      "$temporary_root/metadata.tsv") || fail "ambiguous or missing metadata for $package $version"
    IFS="$(printf '\t')" read -r metadata_name metadata_version current_source manifest current_manifest <<EOF
$metadata_line
EOF
    [ "$manifest" = "$expected_manifest" ] ||
      fail "$package $version manifest license is '$manifest', expected '$expected_manifest'"
    validate_selection "$manifest" "$selected"

    lock_line=$(awk -F '\t' -v package="$package" -v version="$version" \
      '$1 == package && $2 == version { print; found++ } END { if (found != 1) exit 1 }' \
      "$temporary_root/lock.tsv") || fail "ambiguous or missing lock entry for $package $version"
    IFS="$(printf '\t')" read -r lock_name lock_version lock_source current_checksum <<EOF
$lock_line
EOF
    [ "$lock_source" = "$current_source" ] || fail "$package $version source differs between lock and metadata"

    current_root=$(dirname -- "$current_manifest")
    if [ "$current_source" = LOCAL ]; then
      [ "$current_checksum" = LOCAL ] || fail "$package $version local package has a registry checksum"
      current_archive=
      current_prefix=
    else
      [ "$current_checksum" != LOCAL ] || fail "$package $version registry package lacks a lock checksum"
      registry_index=$(dirname -- "$current_root")
      registry_src=$(dirname -- "$registry_index")
      registry_root=$(dirname -- "$registry_src")
      registry_id=$(basename -- "$registry_index")
      current_prefix=$(basename -- "$current_root")
      current_archive="$registry_root/cache/$registry_id/$current_prefix.crate"
      [ -f "$current_archive" ] || fail "cached archive is unavailable for $package $version"
      archive_checksum=$(digest_file "$current_archive")
      [ "$archive_checksum" = "$current_checksum" ] ||
        fail "$package $version cached archive checksum is $archive_checksum, lock records $current_checksum"
      if ! tar -xOf "$current_archive" "$current_prefix/Cargo.toml" \
        >"$temporary_root/archive-manifest"; then
        fail "$package $version cached archive lacks Cargo.toml"
      fi
      cmp -s "$temporary_root/archive-manifest" "$current_manifest" ||
        fail "$package $version extracted Cargo.toml differs from the locked archive"
    fi

    case "$selected" in
      'MIT AND Unicode-3.0')
        printf '%s\t%s\tMIT\n%s\t%s\tUnicode-3.0\n' \
          "$package" "$version" "$package" "$version" >>"$temporary_root/required-expected.tsv"
        ;;
      *)
        printf '%s\t%s\t%s\n' "$package" "$version" "$selected" \
          >>"$temporary_root/required-expected.tsv"
        ;;
    esac
    current_key=$key
  else
    [ "$manifest" = "$expected_manifest" ] || fail "$package $version has inconsistent manifest policy rows"
    validate_selection "$manifest" "$selected"
  fi

  case "$role" in
    selected-license | required-and-license | license-declaration)
      printf '%s\t%s\t%s\n' "$package" "$version" "$required_license" \
        >>"$temporary_root/required-actual.tsv"
      ;;
    attribution-notice | bundled-license | licensing-notice)
      ;;
    *)
      fail "$package $version has unreviewed evidence role '$role'"
      ;;
  esac

  case "$evidence_path" in
    '' | /*) fail "$package $version has unsafe evidence path '$evidence_path'" ;;
  esac

  evidence_file="$current_root/$evidence_path"
  [ -f "$evidence_file" ] || fail "$package $version evidence is unavailable: $evidence_path"
  if [ "$current_source" = LOCAL ]; then
    evidence_directory=$(CDPATH= cd -- "$(dirname -- "$evidence_file")" && pwd -P) ||
      fail "$package $version local evidence directory is unavailable: $evidence_path"
    case "$evidence_directory/" in
      "$repository_root/" | "$repository_root/"*) ;;
      *) fail "$package $version local evidence escapes the repository: $evidence_path" ;;
    esac
    evidence_checksum=$(digest_file "$evidence_file")
  else
    case "$evidence_path" in
      ../* | */../* | */..) fail "$package $version registry evidence escapes its crate: $evidence_path" ;;
    esac
    if ! tar -xOf "$current_archive" "$current_prefix/$evidence_path" \
      >"$temporary_root/archive-evidence"; then
      fail "$package $version cached archive lacks evidence: $evidence_path"
    fi
    cmp -s "$temporary_root/archive-evidence" "$evidence_file" ||
      fail "$package $version extracted evidence differs from the locked archive: $evidence_path"
    evidence_checksum=$(digest_file "$temporary_root/archive-evidence")
  fi

  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
    "$package" "$version" "$current_source" "$current_checksum" "$manifest" "$selected" \
    "$required_license" "$role" "$evidence_path" "$evidence_checksum"
done <"$temporary_root/policy.tsv"

LC_ALL=C sort -u "$temporary_root/required-expected.tsv" >"$temporary_root/required-expected-sorted.tsv"
LC_ALL=C sort -u "$temporary_root/required-actual.tsv" >"$temporary_root/required-actual-sorted.tsv"
diff -u "$temporary_root/required-expected-sorted.tsv" "$temporary_root/required-actual-sorted.tsv" >/dev/null ||
  fail "selected SPDX branches do not have exact required-license evidence"
